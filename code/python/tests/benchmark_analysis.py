import os
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import streamlit as st

# === Streamlit App Setup ===
st.title("📊 ICP Benchmark Analysis Dashboard")
st.caption("Upload a benchmark `summary.csv` file generated by your ICP tests.")

uploaded_file = st.file_uploader("Upload your summary CSV file", type=["csv"])

if uploaded_file is not None:
    df = pd.read_csv(uploaded_file)

    st.success(f"Loaded: `{uploaded_file.name}`")

    icp_methods = df['method'].unique()
    dimensions = df['dimension'].unique()

    st.header("📊 Error Ranges")
    for method in icp_methods:
        for dim in dimensions:
            subset = df[(df['method'] == method) & (df['dimension'] == dim) & df['success']]
            if not subset.empty:
                min_err = subset['rmse_error'].min()
                max_err = subset['rmse_error'].max()
                st.write(f"**{method} ({dim})**: RMSE Range = `{min_err:.4f}` to `{max_err:.4f}`")

    st.header("🏅 Best and Worst Configurations")
    for method in icp_methods:
        for dim in dimensions:
            subset = df[(df['method'] == method) & (df['dimension'] == dim) & df['success']]
            if not subset.empty:
                best = subset.loc[subset['rmse_error'].idxmin()]
                worst = subset.loc[subset['rmse_error'].idxmax()]
                st.markdown(f"### {method} ({dim})")
                st.write("**Best Config:**")
                st.json(best.to_dict())
                st.write("**Worst Config:**")
                st.json(worst.to_dict())

    st.header("📈 Error Distribution by Method & Dimension")
    plt.figure(figsize=(10, 5))
    sns.boxplot(data=df[df['success']], x="method", y="rmse_error", hue="dimension")
    st.pyplot(plt.gcf())

    st.header("📋 Effectiveness by Config Option")
    option_cols = [
        "segmentation_strategy", "memory_mode", "neighborhood_mode",
        "rejection.max_distance", "rejection.max_normal_diff"
    ]
    for col in option_cols:
        plt.figure(figsize=(10, 4))
        sns.boxplot(data=df[df['success']], x=col, y="rmse_error")
        plt.xticks(rotation=30)
        plt.title(f"Effect of `{col}` on Error")
        st.pyplot(plt.gcf())

    st.header("📊 2D vs 3D Comparison")
    dim_comp = df[df['success']].groupby(['method', 'dimension'])['rmse_error'].agg(['mean', 'min', 'max', 'count']).reset_index()
    st.dataframe(dim_comp)

    st.header("🏁 Overall Method Performance")
    summary = df[df['success']].groupby('method')['rmse_error'].agg(['mean', 'min', 'max', 'count']).sort_values('mean')
    st.dataframe(summary)
    best_method = summary.index[0]
    st.success(f"🥇 Best performing method: **{best_method}**")
else:
    st.info("Please upload a summary CSV file to begin analysis.")
